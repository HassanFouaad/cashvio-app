/**
 * Context-aware rewrite for remaining banned chars.
 * @param {string} value
 * @param {string} pathKey
 */
function rewriteHeuristic(value, pathKey) {
  let s = value;

  // Numeric ranges with en-dash
  s = s.replace(/(\d+)\u2013(\d+)/g, '$1 إلى $2');

  // Ledger eyebrows / NO. style
  if (
    /^رقم\s+\d+\s+\u2014/.test(s) ||
    pathKey.includes('eyebrow') && /^رقم\s+/.test(s)
  ) {
    return s.replace(/\s*\u2014\s*/g, ' · ');
  }

  // Ticker / receipt-like
  if (pathKey.includes('ticker') || /^\d{2}:\d{2}\s+\u2014/.test(s)) {
    return s.replace(/\s*\u2014\s*/g, ' · ');
  }

  // Live preview captions
  if (s.startsWith('عرض مباشر')) {
    return s.replace(/\s*\u2014\s*/g, ': ');
  }

  // Meta titles
  if (/^metadata\.[^.]+\.title$/.test(pathKey)) {
    return s.replace(/\s*\u2014\s*/g, ': ');
  }

  // FAQ yes/no openers
  s = s.replace(/^(نعم|لا)\s+\u2014\s+/u, '$1. ');

  // Done / تم
  s = s.replace(/^تم\s+\u2014\s+/u, 'تم. ');

  // Author "role — city"
  if (
    pathKey.includes('.author') ||
    /^(صاحب|صاحبة)\s/.test(s) && (s.match(/\u2014/g) || []).length === 1
  ) {
    return s.replace(/\s*\u2014\s*/g, '، ');
  }

  // Label — definition (privacy/terms/list items): short left clause
  // Replace paired asides " — X — " first
  s = s.replace(/\s+\u2014\s+([^—\u2014]{1,80}?)\s+\u2014\s+/gu, '، $1، ');

  // Remaining single em-dashes: pick separator from right-hand cue
  s = s.replace(/\s+\u2014\s+/gu, (match, offset, full) => {
    const right = full.slice(offset + match.length);
    const left = full.slice(0, offset);

    // Right starts with connector already
    if (/^(و|أو|مع|أي|مثل|بما|بدون|ب|ل|ف|ثم)/u.test(right)) {
      if (/^(و|أو|مع|أي|مثل|بما)/u.test(right)) return '، ';
      if (/^(بدون)/u.test(right)) return '، ';
      return '، ';
    }

    // Free-forever / مجانا closers
    if (/^(مجاني|مجانا|مجان)/u.test(right)) return '. ';

    // Explanation after short label (no sentence end on left)
    const leftTail = left.split(/[.!?\n]/u).pop() || left;
    if (leftTail.trim().length <= 48 && !/[.!?،:]$/u.test(left.trim())) {
      return ': ';
    }

    // Default prose break
    return '. ';
  });

  // Any leftover banned (no spaces)
  s = s.replace(/\u2014/g, '،');
  s = s.replace(/\u2013/g, ' إلى ');
  s = s.replace(/\u2192/g, '،');

  // Clean double spaces / awkward "إلى  إلى"
  s = s.replace(/\s{2,}/g, ' ');
  s = s.replace(/إلى\s+إلى/g, 'إلى');

  return s;
}

/**
 * @param {string} value
 * @param {string} pathKey
 */
function rewrite(value, pathKey) {
  if (!BANNED.test(value)) return value;
  if (Object.prototype.hasOwnProperty.call(OVERRIDES, value)) {
    return OVERRIDES[value];
  }
  return rewriteHeuristic(value, pathKey);
}

/**
 * @param {unknown} node
 * @param {string} pathKey
 * @param {{rewritten: number, samples: Array<{path: string, before: string, after: string}>}} stats
 */
function walk(node, pathKey, stats) {
  if (typeof node === 'string') {
    if (!BANNED.test(node)) return node;
    const after = rewrite(node, pathKey);
    if (after !== node) {
      stats.rewritten += 1;
      if (stats.samples.length < 5) {
        stats.samples.push({ path: pathKey, before: node, after });
      }
    }
    if (BANNED.test(after)) {
      stats.failed.push({ path: pathKey, value: after });
    }
    return after;
  }
  if (Array.isArray(node)) {
    return node.map((item, i) => walk(item, `${pathKey}[${i}]`, stats));
  }
  if (node && typeof node === 'object') {
    /** @type {Record<string, unknown>} */
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      const next = pathKey ? `${pathKey}.${k}` : k;
      out[k] = walk(v, next, stats);
    }
    return out;
  }
  return node;
}

